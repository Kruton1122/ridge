#!/usr/bin/env python3
"""Ridge Voice board: scrape AA's Speech to Speech page into src/lib/data/voice.ts.

Separate from the text ledger on purpose. Copies AA's table cells as shown
("-" becomes null); never fills gaps. Refuses to write if the table header
moved or fewer than 10 rows parse, so a broken page cannot blank the board.
Usage: voice-s2s.py [--from FILE] [--dry-run]
"""
import datetime, html, json, os, re, subprocess, sys

URL = "https://artificialanalysis.ai/speech-to-speech"
UA = "Mozilla/5.0 (X11; Linux x86_64) Chrome/130"
REPO = os.environ.get("RIDGE_HOME", os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
OUT = os.path.join(REPO, "src/lib/data/voice.ts")
WANT = {
    "Provider": "provider", "Model": "model", "Speech to Speech Index": "index",
    "Speech Reasoning %": "reasoning", "Conversational Dynamics %": "dynamics",
    "Agentic Performance %": "agentic", "Arena Preference Elo": "arenaElo",
    "Task Success Rate %": "taskSuccess", "Time to First Audio Seconds": "ttfa",
}

def clean(x):
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", x))).strip()

def parse(raw):
    for tb in re.findall(r"<table.*?</table>", raw, re.S):
        rows = [[clean(c) for c in re.findall(r"<t[hd][^>]*>(.*?)</t[hd]>", tr, re.S)]
                for tr in re.findall(r"<tr.*?</tr>", tb, re.S)]
        if not rows or "Speech to Speech Index" not in rows[0]:
            continue
        hdr = rows[0]
        missing = [h for h in WANT if h not in hdr]
        if missing:
            raise SystemExit(f"voice: header changed, missing {missing}")
        out = []
        for r in rows[1:]:
            if len(r) != len(hdr):
                continue
            d = {}
            for h, k in WANT.items():
                v = r[hdr.index(h)]
                d[k] = None if v in ("-", "", "—") else v
            if d["provider"] and d["model"]:
                out.append(d)
        return out
    raise SystemExit("voice: Speech to Speech Index table not found")

def num(v):
    try: return float(str(v).rstrip("%"))
    except (TypeError, ValueError): return None

def render(rows, as_of):
    J = json.dumps
    lines = [
        "// Generated by scripts/voice-s2s.py from Artificial Analysis's Speech to Speech page.",
        "// Do not hand-edit scores. Cells are copied as AA shows them; null means AA shows no value.",
        "// Voice models live here, not in catalog.ts: they are not part of the text ledger.",
        "",
        "export interface VoiceRow {",
        "  provider: string;",
        "  model: string;",
        "  /** AA Speech to Speech Index, as displayed. */",
        "  index: string | null;",
        "  reasoning: string | null;",
        "  dynamics: string | null;",
        "  agentic: string | null;",
        "  arenaElo: string | null;",
        "  taskSuccess: string | null;",
        "  /** Time to first audio, seconds. */",
        "  ttfa: string | null;",
        "}",
        "",
        f"export const VOICE_AS_OF = {J(as_of)};",
        f"export const VOICE_SOURCE = {{ name: \"Artificial Analysis\", url: {J(URL)} }};",
        "",
        "export const VOICE_ROWS: VoiceRow[] = [",
    ]
    for d in rows:
        lines.append("  { " + ", ".join(f"{k}: {J(d[k])}" for k in WANT.values()) + " },")
    lines += ["];", ""]
    return "\n".join(lines)

def main():
    args = sys.argv[1:]
    raw = open(args[args.index("--from") + 1], errors="ignore").read() if "--from" in args else \
        subprocess.run(["curl", "-sL", "--compressed", "-A", UA, "-m", "60", URL], capture_output=True, text=True).stdout
    rows = parse(raw)
    if len(rows) < 10:
        raise SystemExit(f"voice: only {len(rows)} rows parsed, not writing")
    rows.sort(key=lambda d: (num(d["index"]) is None, -(num(d["index"]) or 0), d["provider"], d["model"]))
    old = open(OUT).read() if os.path.exists(OUT) else ""
    strip = lambda s: re.sub(r'export const VOICE_AS_OF = "[^"]*";', "", s)
    as_of = datetime.date.today().isoformat()
    new = render(rows, as_of)
    scored = [d for d in rows if d["index"]]
    lead = f"{scored[0]['model']} {scored[0]['index']}" if scored else "none"
    changed = strip(new) != strip(old)
    if "--dry-run" not in args:
        open(OUT, "w").write(new)
    print(f"voice: {len(rows)} rows, {len(scored)} with Index, leader {lead}{'' if changed else ', scores unchanged'}")

if __name__ == "__main__":
    main()
